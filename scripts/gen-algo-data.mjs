// Writes src/features/algo-lab/data.ts from the curriculum below and the lesson files that exist.
//   node scripts/gen-algo-data.mjs
// A lesson that has no file yet is skipped, so the course grows as lessons are added.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../src/features/algo-lab");

const MODULES = [
  ["foundations", "Foundations", "#d5b07a", "big-o memory recursion divide-and-conquer"],
  [
    "arrays",
    "Arrays & Strings",
    "#3fa456",
    "arrays dynamic-arrays two-pointers sliding-window prefix-sums maximum-subarray merge-intervals pattern-matching kmp matrices",
  ],
  [
    "linked-lists",
    "Linked Lists",
    "#7c63d0",
    "linked-lists doubly-linked-lists fast-slow reversing-a-list merge-sorted-lists lru-cache",
  ],
  [
    "stacks-queues",
    "Stacks & Queues",
    "#e8834d",
    "stacks balanced-brackets queues circular-buffer deques monotonic-stack monotonic-queue",
  ],
  [
    "hashing",
    "Hashing",
    "#2f86ce",
    "hash-tables collision-handling resizing sets-and-maps bloom-filters",
  ],
  [
    "trees",
    "Trees",
    "#2a9d8f",
    "binary-trees tree-traversals lowest-common-ancestor binary-search-trees bst-deletion balanced-trees tries segment-trees",
  ],
  [
    "heaps",
    "Heaps",
    "#d9577a",
    "binary-heaps building-a-heap priority-queues top-k median-of-a-stream heap-sort",
  ],
  [
    "graphs",
    "Graphs",
    "#8c9a3c",
    "graph-representation breadth-first-search depth-first-search connected-components cycle-detection topological-sort strongly-connected-components shortest-paths bellman-ford floyd-warshall union-find minimum-spanning-trees prims-algorithm",
  ],
  [
    "sorting",
    "Sorting & Searching",
    "#64728a",
    "binary-search binary-search-on-answer simple-sorts merge-sort quick-sort quickselect counting-radix-sort stability-and-limits",
  ],
  [
    "greedy",
    "Greedy Algorithms",
    "#c9a227",
    "interval-scheduling huffman-coding when-greedy-fails",
  ],
  ["backtracking", "Backtracking", "#a0522d", "subsets permutations n-queens maze"],
  [
    "dp",
    "Dynamic Programming",
    "#6a5acd",
    "memoization tabulation grid-paths knapsack coin-change longest-increasing-subsequence sequences edit-distance",
  ],
  ["bits", "Bit Manipulation", "#20b2aa", "bits-and-masks bit-tricks bitsets"],
  ["hard", "Hard Problems", "#b22222", "p-vs-np"],
];

const imports = [];
const modules = [];
let n = 0;
let missing = 0;
for (const [id, name, color, list] of MODULES) {
  const names = [];
  for (const lesson of list.split(" ")) {
    const file = `${root}/lessons/${lesson}.ts`;
    if (!existsSync(file)) {
      missing++;
      continue;
    }
    const match = readFileSync(file, "utf8").match(/export const (\w+): AlgoLesson/);
    if (!match) throw new Error(`${lesson}.ts has no "export const x: AlgoLesson"`);
    imports.push(`import { ${match[1]} } from "./lessons/${lesson}";`);
    names.push(match[1]);
    n++;
  }
  if (names.length) modules.push({ id, name, color, names });
}

const body = modules
  .map((m) => {
    const i = MODULES.findIndex(([id]) => id === m.id) + 1;
    return `  {\n    id: "${m.id}",\n    name: "${String(i).padStart(2, "0")}. ${m.name.replace(/"/g, '\\"')}",\n    color: "${m.color}",\n    lessons: [${m.names.join(", ")}],\n  },`;
  })
  .join("\n");

writeFileSync(
  `${root}/data.ts`,
  `// Generated by scripts/gen-algo-data.mjs: edit the curriculum there, not here.
${imports.sort().join("\n")}
import type { AlgoModule } from "./lib/types";

/** The course, in reading order. Each lesson is plain data in \`lessons/\`. */
export const MODULES: readonly AlgoModule[] = [
${body}
];
`,
);
console.log(`${n} lessons wired, ${missing} not written yet`);
